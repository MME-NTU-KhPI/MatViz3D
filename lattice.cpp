void Lattice::report() const
{
    qInfo().noquote()
        << QString("[Lattice] %1: %2 cells per edge (%3 voxels per cell), target relative "
                   "density %4, level c = %5, material %6")
               .arg(latticeFamilyLabel(m_family)).arg(m_cells)
               .arg(static_cast<double>(numCubes) / m_cells, 0, 'f', 1)
               .arg(m_target, 0, 'f', 3).arg(m_c, 0, 'g', 4).arg(m_material);

    if (m_segments2D)
        qInfo().noquote()
            << QString("[Lattice] honeycomb: %1 cells along Y; cells stretched by %2 along Y "
                       "to tile the square cube%3")
                   .arg(m_cellsY).arg(m_hcStretch, 0, 'f', 3)
                   .arg(m_hcCustom ? QString("; custom shape: wall angle %1 deg, rib %2")
                                         .arg(m_hcAngle, 0, 'f', 1).arg(m_hcRib, 0, 'f', 2)
                                   : QString());

    if (m_family == LatticeFamily::Spinodoid)
        qInfo().noquote()
            << QString("[Lattice] spinodoid: cones about X/Y/Z = %1/%2/%3 deg, %4 admissible directions, %5 waves (seed %6)")
                   .arg(m_theta[0], 0, 'f', 0).arg(m_theta[1], 0, 'f', 0).arg(m_theta[2], 0, 'f', 0)
                   .arg(m_directions).arg(m_waves.size()).arg(Parameters::seed);
    if (m_family == LatticeFamily::NoiseSheet || m_family == LatticeFamily::NoiseSkeletal)
        qInfo().noquote()
            << QString("[Lattice] smoothed noise: sigma %1 of the edge = %2 voxels of the %3^3 noise grid (seed %4)")
                   .arg(m_noiseSmooth, 0, 'g', 3).arg(m_noiseSigmaVox, 0, 'f', 1).arg(kNoiseGrid).arg(Parameters::seed);
    if (m_family == LatticeFamily::FourierSheet || m_family == LatticeFamily::FourierSkeletal)
        qInfo().noquote()
            << QString("[Lattice] Fourier series: %1 waves%2 (|k| in [%3, %4] per edge, decay %5, seed %6)%7")
                   .arg(m_waves.size())
                   .arg(m_fourierFile.isEmpty() ? QString() : QString(" from \"%1\"").arg(m_fourierFile))
                   .arg(m_fourierKmin, 0, 'g', 3).arg(m_fourierKmax, 0, 'g', 3)
                   .arg(m_fourierDecay, 0, 'g', 3).arg(Parameters::seed)
                   .arg(m_cubicSym ? QStringLiteral(", cubic symmetry (waves expanded to their orbits)") : QString());
    if (isPlateFamily(m_family) || (m_hasUnion && isPlateFamily(m_union)))
        qInfo().noquote()
            << QString("[Lattice] plate lattice: plane families %1%2")
                   .arg([&]{ const int o = plateOrientations(isPlateFamily(m_family) ? m_family : m_union);
                             QStringList l; if (o & 1) l << "{100}"; if (o & 2) l << "{110}"; if (o & 4) l << "{111}"; return l.join("+"); }())
                   .arg(m_plateHole > 0.0 ? QString(", holes of %1 cell edges through the panel centres").arg(m_plateHole, 0, 'g', 3) : QString());
    if (m_hasFoam) {
        size_t faces = 0, edges = 0;
        for (const FoamCell& c : m_foamCells) { faces += c.faces.size(); edges += c.edges.size(); }
        const double nc = std::max<double>(1.0, static_cast<double>(m_foamCells.size()));
        qInfo().noquote()
            << QString("[Lattice] foam: %1 bubble(s) per cell (%2), %3 faces and %4 edges per bubble on average, "
                       "bubble size %5 cell edges; %6")
                   .arg(m_foamSites.size())
                   .arg(m_foamFamily != LatticeFamily::FoamRandom ? latticeFamilyKey(m_foamFamily)
                        : (m_foamFile.isEmpty() ? QString("random, seed %1").arg(Parameters::seed) : QString("from \"%1\"").arg(m_foamFile)))
                   .arg(static_cast<double>(faces) / nc, 0, 'f', 2).arg(static_cast<double>(edges) / nc, 0, 'f', 2)
                   .arg(m_foamBubble, 0, 'f', 3)
                   .arg(m_foamMode == QLatin1String("edges") ? QStringLiteral("edges only (open cells)")
                        : m_foamMode == QLatin1String("windows") ? QString("walls with a window in every face, frame %1 bubble sizes").arg(m_foamFrame, 0, 'g', 3)
                        : QStringLiteral("closed walls"));
    }
    if (m_family == LatticeFamily::CubicAssembly) {
        int n[4] = { 0, 0, 0, 0 };
        double wlo = 1e300, whi = 0.0;
        for (const Member& m : m_members) {
            ++n[std::clamp(m.kind, 0, 3)];
            if (m.kind != Member::Hole) { wlo = std::min(wlo, m.w); whi = std::max(whi, m.w); }
        }
        qInfo().noquote()
            << QString("[Lattice] cubic assembly: %1 struts, %2 plates, %3 shells, %4 windows in the asymmetric unit, "
                       "repeated by the 48 cube symmetries; thickness weights %5..%6 (%7)")
                   .arg(n[0]).arg(n[1]).arg(n[2]).arg(n[3])
                   .arg(wlo < 1e300 ? wlo : 1.0, 0, 'f', 2).arg(whi, 0, 'f', 2)
                   .arg(m_asmFile.isEmpty() ? QString("seed %1").arg(Parameters::seed) : QString("from \"%1\"").arg(m_asmFile));
    }
    if (m_family == LatticeFamily::Mycelium) {
        const mycelium::Stats& st = m_mycStats;
        const QString origin = st.grown
                                   ? QString("%1, seed %2").arg(QString::fromLatin1(mycelium::modeKey(m_myc.mode))).arg(Parameters::seed)
                                   : QString("from \"%1\"").arg(m_mycFile);
        qInfo().noquote()
            << QString("[Lattice] mycelium (%1): %2 pieces, hypha length %3 cell edges%4; thinnest hypha weight %5, "
                       "field exact below %6 cell edges (%7^3 buckets)")
                   .arg(origin).arg(m_mycSegments.size()).arg(st.length, 0, 'f', 2)
                   .arg(st.grown ? QString(", %1 hyphae, %2 branchings, %3 fusions, %4 free ends, growth unit %5, "
                                           "%6 % of the length on closed loops")
                                       .arg(st.hyphae).arg(st.branches).arg(st.fusions).arg(st.freeEnds)
                                       .arg(st.growthUnit, 0, 'f', 3).arg(100.0 * st.backbone, 0, 'f', 0)
                                 : QString())
                   .arg(m_mycMinWeight, 0, 'f', 3).arg(m_mycCut, 0, 'g', 3).arg(m_mycG);
    }
    if (isFormFamily(m_family)) {
        const auto kind = static_cast<cellforms::Kind>(formIndex(m_family));
        const double v[3] = { m_formKnobs.a, m_formKnobs.b, m_formKnobs.c };
        QStringList knobs;
        for (int k = 0; k < 3; ++k)
            if (const char* l = cellforms::knobLabel(kind, k))
                knobs << QString("%1 %2").arg(QString::fromLatin1(l)).arg(v[k], 0, 'g', 3);
        qInfo().noquote()
            << QString("[Lattice] form: %1%2%3")
                   .arg(knobs.join(QStringLiteral(", ")))
                   .arg(usesPieceTable() ? QString("; %1 pieces, thinnest weight %2, field exact below %3 cell edges")
                                               .arg(m_mycSegments.size()).arg(m_mycMinWeight, 0, 'f', 2).arg(m_mycCut, 0, 'g', 3)
                                         : QString())
                   .arg(isRandomFamily(m_family) ? QString(" (seed %1)").arg(Parameters::seed) : QString());
    }
    if (m_hasUnion)
        qInfo().noquote()
            << QString("[Lattice] united with %1 (one level c for both)").arg(latticeFamilyLabel(m_union));
    if (m_hasSubtract)
        qInfo().noquote()
            << QString("[Lattice] carved out: %1 up to level %2 cell units").arg(latticeFamilyLabel(m_subtract)).arg(m_subtractSize, 0, 'g', 3);
    if (m_smooth > 0.0)
        qInfo().noquote()
            << QString("[Lattice] field smoothed with sigma %1 cell edges = %2 voxels")
                   .arg(m_smooth, 0, 'g', 3).arg(m_smooth * numCubes / m_cells, 0, 'f', 1);

    if (m_rotated)
        qInfo().noquote()
            << QString("[Lattice] lattice rotated by (%1, %2, %3) deg about the cube centre; "
                       "the cut is no longer periodic across the cube faces")
                   .arg(m_angles[0] * 180.0 / M_PI, 0, 'f', 1)
                   .arg(m_angles[1] * 180.0 / M_PI, 0, 'f', 1)
                   .arg(m_angles[2] * 180.0 / M_PI, 0, 'f', 1);

    if (m_grading > 0.0 || m_jitter > 0.0)
        qInfo().noquote()
            << QString("[Lattice] thickness grading %1 along Z, jitter %2 (seed %3)")
                   .arg(m_grading, 0, 'f', 2).arg(m_jitter, 0, 'f', 2).arg(Parameters::seed);

    if (m_wallVox > 0.0 && m_wallVox < 6.0)
        qWarning().noquote()
            << QString("[Lattice] estimated wall/strut thickness is only %1 voxels; below ~6 "
                       "the voxel staircase distorts the homogenized stiffness -- raise the "
                       "cube size or the relative density")
                   .arg(m_wallVox, 0, 'f', 1);
}

void Lattice::reportAchieved() const
{
    QString wall = m_wallVox > 0.0
                       ? QString(", estimated wall/strut thickness %1 voxels").arg(m_wallVox, 0, 'f', 1)
                       : QString();
    qInfo().noquote()
        << QString("[Lattice] achieved relative density %1 (target %2)%3")
               .arg(m_achieved, 0, 'f', 4).arg(m_target, 0, 'f', 3).arg(wall);
}

