void Lattice::readParameters()
{
    Parameters& p = *Parameters::instance();

    LatticeFamily f = LatticeFamily::GyroidSheet;
    if (!parseLatticeFamily(p.getLatticeFamily(), f)) {
        qWarning().noquote() << QString("[Lattice] unknown cell family \"%1\"; using Gyroid (sheet)")
                                    .arg(p.getLatticeFamily());
        f = LatticeFamily::GyroidSheet;
    }
    m_family = f;
    m_signed = latticeFamilyInfo(f).signedLevelSet;

    m_uniformWall = p.getLatticeUniformWall();
    m_cells    = std::clamp(p.getCellsPerEdge(), 1, 64);
    m_target   = std::clamp(p.getRelativeDensity(), 0.01, 0.99);
    m_grading  = std::clamp(p.getLatticeGrading(), 0.0, 0.9);
    m_jitter   = std::clamp(p.getLatticeJitter(), 0.0, 1.0);
    m_periodic = flags.isPeriodicStructure || p.getIsPeriodic();

    // A lattice without a material would silently be solved as the solvers'
    // fallback (copper). Default to the printed polymer the cell is meant for
    // and say so, and write it back so the HDF5 metadata matches what ran.
    m_material = p.getDbMaterial();
    if (Parameters::materialOverrideActive()) {
        m_material = Parameters::overrideMaterialName();
    } else if (m_material.isEmpty()) {
        m_material = QStringLiteral("PETG");
        p.setDbMaterial(m_material);
        qInfo() << "[Lattice] no material selected; using PETG";
    }

    const double d2r = M_PI / 180.0;
    m_angles[0] = p.getOrientationAngleA() * d2r;
    m_angles[1] = p.getOrientationAngleB() * d2r;
    m_angles[2] = p.getOrientationAngleC() * d2r;

    m_theta[0] = std::clamp(p.getSpinodoidThetaX(), 0.0, 90.0);
    m_theta[1] = std::clamp(p.getSpinodoidThetaY(), 0.0, 90.0);
    m_theta[2] = std::clamp(p.getSpinodoidThetaZ(), 0.0, 90.0);
    if (m_theta[0] <= 0.0 && m_theta[1] <= 0.0 && m_theta[2] <= 0.0) {
        qWarning() << "[Lattice] all spinodoid cones are closed; using the isotropic field";
        m_theta[0] = m_theta[1] = m_theta[2] = 90.0;
    }

    m_fourierTerms = std::clamp(p.getFourierTerms(), 2, 256);
    m_fourierKmin  = std::max(1.0, p.getFourierKmin());
    m_fourierKmax  = std::max(m_fourierKmin, p.getFourierKmax());
    m_fourierDecay = std::clamp(p.getFourierDecay(), 0.0, 4.0);
    m_fourierFile  = p.getFourierFile();
    m_cubicSym     = p.getFourierSymmetry().compare(QLatin1String("cubic"), Qt::CaseInsensitive) == 0;
    m_noiseSmooth  = std::clamp(p.getNoiseSmooth(), 0.005, 0.5);
    m_hcCustom     = p.getHoneycombCustom();
    m_hcAngle      = std::clamp(p.getHoneycombAngle(), -50.0, 50.0);
    m_hcRib        = std::clamp(p.getHoneycombRib(), 0.2, 5.0);
    if (m_hcCustom && m_hcRib + std::sin(m_hcAngle * M_PI / 180.0) <= 0.1) {
        qWarning().noquote() << QString("[Lattice] honeycomb angle %1 deg with rib %2 folds the cell onto itself; using the family preset")
                                    .arg(m_hcAngle, 0, 'f', 1).arg(m_hcRib, 0, 'f', 2);
        m_hcCustom = false;
    }
    m_plateHole    = std::clamp(p.getPlateHole(), 0.0, 0.9);
    m_metric[0]    = 1.0;
    m_metric[1]    = std::clamp(p.getLatticeMetricY(), 0.25, 4.0);
    m_metric[2]    = std::clamp(p.getLatticeMetricZ(), 0.25, 4.0);
    m_metricOn     = m_metric[1] != 1.0 || m_metric[2] != 1.0;
    for (int i = 0; i < 3; ++i) {
        const int j = (i + 1) % 3;
        m_plateDen110[i] = std::sqrt(1.0 / (m_metric[i] * m_metric[i]) + 1.0 / (m_metric[j] * m_metric[j]));   // sqrt(2) without the metric
    }
    m_plateDen111 = std::sqrt(1.0 / (m_metric[0] * m_metric[0]) + 1.0 / (m_metric[1] * m_metric[1]) + 1.0 / (m_metric[2] * m_metric[2]));
    if (m_metricOn) {
        const bool used = metricApplies(m_family);
        qInfo().noquote() << QString("[Lattice] thickness metric x 1, y %1, z %2%3").arg(m_metric[1], 0, 'g', 4).arg(m_metric[2], 0, 'g', 4)
                             .arg(used ? QString() : QStringLiteral(" - IGNORED: this family is not measured by distances (struts, plates, cubic assembly, uniform-wall sheets are)"));
    }
    m_smooth       = std::clamp(p.getLatticeSmooth(), 0.0, 0.3);
    m_subtractSize = std::clamp(p.getLatticeSubtractSize(), 0.01, 1.0);
    m_asmStruts    = std::clamp(p.getAssemblyStruts(), 0, 12);
    m_asmPlates    = std::clamp(p.getAssemblyPlates(), 0, 12);
    m_asmShells    = std::clamp(p.getAssemblyShells(), 0, 4);
    m_asmHoles     = std::clamp(p.getAssemblyHoles(), 0, 8);
    m_asmSpread    = std::clamp(p.getAssemblySpread(), 0.0, 0.8);
    m_asmFile      = p.getAssemblyFile();
    m_foamMode     = p.getFoamMode();
    m_foamFrame    = std::clamp(p.getFoamFrame(), 0.01, 0.5);
    m_foamBubbles  = std::clamp(p.getFoamBubbles(), 1, 64);
    m_foamFile     = p.getFoamFile();
    m_myc = mycelium::Params();
    if (!mycelium::parseMode(p.getMyceliumMode().toLatin1().constData(), m_myc.mode))
        m_myc.mode = mycelium::Mode::Substrate;
    m_myc.length  = std::clamp(p.getMyceliumLength(), 2.0, 80.0);
    m_myc.spores  = std::clamp(p.getMyceliumSpores(), 0, 40);
    m_myc.unit    = std::clamp(p.getMyceliumUnit(), 0.05, 2.0);
    m_myc.angle   = std::clamp(p.getMyceliumAngle(), 10.0, 90.0);
    m_myc.wiggle  = std::clamp(p.getMyceliumWiggle(), 0.0, 1.0);
    m_myc.fuse    = std::clamp(p.getMyceliumFuse(), 0.0, 0.2);
    m_myc.taper   = std::clamp(p.getMyceliumTaper(), 0.3, 1.0);
    m_myc.binding = std::clamp(p.getMyceliumBinding(), 0.0, 0.8);
    m_myc.align   = std::clamp(p.getMyceliumAlign(), 0.0, 1.0);
    m_myc.anchors = std::clamp(p.getMyceliumAnchors(), 0.0, 1.0);
    m_myc.poor    = std::clamp(p.getMyceliumPoor(), 0.05, 1.0);
    m_mycFile     = p.getMyceliumFile();
    m_formKnobs.a = std::clamp(p.getFormA(), 0.0, 1.0);
    m_formKnobs.b = std::clamp(p.getFormB(), 0.0, 1.0);
    m_formKnobs.c = std::clamp(p.getFormC(), 0.0, 1.0);

    // Second and third families (united with / carved out of the first).
    // Random families keep state in the same members as the primary, and
    // segment families share one segment table, so those pairs are refused.
    m_hasUnion = m_hasSubtract = false;
    auto resolve = [&](const QString& key, const char* what, LatticeFamily& out) -> bool {
        if (key.isEmpty()) return false;
        LatticeFamily u;
        if (!parseLatticeFamily(key, u)) {
            qWarning().noquote() << QString("[Lattice] unknown %1 family \"%2\"; ignored").arg(what, key);
            return false;
        }
        if (u == m_family) {
            qWarning().noquote() << QString("[Lattice] %1 equals the cell family; ignored").arg(what);
            return false;
        }
        if (isFormFamily(u)) {
            qWarning().noquote() << QString("[Lattice] %1 cannot be a bio-inspired / architected form (%2); ignored").arg(what, key);
            return false;
        }
        if (isRandomFamily(u)) {
            qWarning().noquote() << QString("[Lattice] %1 cannot be a random family (%2); ignored").arg(what, key);
            return false;
        }
        const bool segTaken = isSegmentFamily(m_family) || (m_hasUnion && isSegmentFamily(m_union));
        if (isSegmentFamily(u) && segTaken) {
            qWarning().noquote() << QString("[Lattice] only one strut/honeycomb family per cell; %1 = %2 ignored").arg(what, key);
            return false;
        }
        const bool foamTaken = isFoamFamily(m_family) || (m_hasUnion && isFoamFamily(m_union));
        if (isFoamFamily(u) && foamTaken) {
            qWarning().noquote() << QString("[Lattice] only one foam family per cell; %1 = %2 ignored").arg(what, key);
            return false;
        }
        out = u;
        return true;
    };
    m_hasUnion    = resolve(Parameters::latticeUnionKeyStored(),    "lattice_union",    m_union);
    m_hasSubtract = resolve(Parameters::latticeSubtractKeyStored(), "lattice_subtract", m_subtract);
}

// R = Rz(a) * Rx(b) * Rz(c), applied to coordinates about the cube centre.
void Lattice::buildRotation()
{
    const double a = m_angles[0], b = m_angles[1], c = m_angles[2];
    m_rotated = std::abs(a) > 1e-12 || std::abs(b) > 1e-12 || std::abs(c) > 1e-12;

    const double ca = std::cos(a), sa = std::sin(a);
    const double cb = std::cos(b), sb = std::sin(b);
    const double cc = std::cos(c), sc = std::sin(c);
    const double Rz1[3][3] = { { ca, -sa, 0.0 }, { sa, ca, 0.0 }, { 0.0, 0.0, 1.0 } };
    const double Rx [3][3] = { { 1.0, 0.0, 0.0 }, { 0.0, cb, -sb }, { 0.0, sb, cb } };
    const double Rz2[3][3] = { { cc, -sc, 0.0 }, { sc, cc, 0.0 }, { 0.0, 0.0, 1.0 } };

    double T[3][3];
    for (int i = 0; i < 3; ++i)
        for (int j = 0; j < 3; ++j) {
            double s = 0.0;
            for (int k = 0; k < 3; ++k) s += Rz1[i][k] * Rx[k][j];
            T[i][j] = s;
        }
    for (int i = 0; i < 3; ++i)
        for (int j = 0; j < 3; ++j) {
            double s = 0.0;
            for (int k = 0; k < 3; ++k) s += T[i][k] * Rz2[k][j];
            m_R[i][j] = s;
        }
}

void Lattice::buildSegments()
{
    m_segments.clear();
    m_segments2D = false;
    m_hcW = m_hcP = 1.0;
    m_cellsY = m_cells;
    m_hcStretch = 1.0;

    auto add = [&](double ax, double ay, double az, double bx, double by, double bz) {
        m_segments.push_back({ ax, ay, az, bx, by, bz });
    };

    // The six face diagonals of the unit cube (opposite faces coincide under
    // periodicity, so one face per axis is enough).
    auto addFcc = [&]() {
        add(0, 0, 0,  0, 1, 1);  add(0, 1, 0,  0, 0, 1);   // face x = 0
        add(0, 0, 0,  1, 0, 1);  add(1, 0, 0,  0, 0, 1);   // face y = 0
        add(0, 0, 0,  1, 1, 0);  add(1, 0, 0,  0, 1, 0);   // face z = 0
    };

    // Hexagonal honeycomb family in wall-length units (l = 1): vertical ribs
    // of length h at x = 0 and, staggered by half a period, at x = W/2;
    // inclined walls of length 1 at angle theta to the horizontal join the end
    // of each rib to the ends of its two staggered neighbours. theta > 0 is
    // the regular hexagon, theta < 0 folds the walls inward (re-entrant,
    // auxetic). Periodic images supply the rest of the tiling.
    auto honeycomb = [&](double thetaDeg, double h) {
        const double th = thetaDeg * M_PI / 180.0;
        const double W  = 2.0 * std::cos(th);
        const double P  = 2.0 * (h + std::sin(th));
        m_hcW = W;
        m_hcP = P;
        m_segments2D = true;

        add(0.0, 0.0, 0.0,  0.0, h, 0.0);
        add(W / 2, P / 2, 0.0,  W / 2, P / 2 + h, 0.0);
        add(0.0, h, 0.0,   W / 2, P / 2, 0.0);
        add(0.0, h, 0.0,  -W / 2, P / 2, 0.0);
        add(0.0, 0.0, 0.0,  W / 2, P / 2 + h - P, 0.0);
        add(0.0, 0.0, 0.0, -W / 2, P / 2 + h - P, 0.0);

        // A hexagonal tiling has period P along Y for every W along X, so a
        // square cube cannot hold whole cells both ways. Round the count along
        // Y and stretch the cells to fit; the factor is reported.
        const double ideal = m_cells * W / P;
        m_cellsY    = std::max(1, static_cast<int>(std::lround(ideal)));
        m_hcStretch = (m_cells * W) / (m_cellsY * P);
    };

    // The segment table belongs to whichever of the families needs it (at most one).
    LatticeFamily segFam = m_family;
    if (!isSegmentFamily(segFam) && m_hasUnion && isSegmentFamily(m_union))       segFam = m_union;
    if (!isSegmentFamily(segFam) && m_hasSubtract && isSegmentFamily(m_subtract)) segFam = m_subtract;
    switch (segFam) {
        case LatticeFamily::SimpleCubic:
            add(0, 0, 0,  1, 0, 0);  add(0, 0, 0,  0, 1, 0);  add(0, 0, 0,  0, 0, 1);
            break;
        case LatticeFamily::BCC:
            add(0, 0, 0,  1, 1, 1);  add(1, 0, 0,  0, 1, 1);
            add(0, 1, 0,  1, 0, 1);  add(0, 0, 1,  1, 1, 0);
            break;
        case LatticeFamily::FCC:
            addFcc();
            break;
        case LatticeFamily::Octet: {
            addFcc();
            // The inner octahedron: edges between the centres of adjacent faces.
            const double c[6][3] = { { 0.0, 0.5, 0.5 }, { 1.0, 0.5, 0.5 },
                                     { 0.5, 0.0, 0.5 }, { 0.5, 1.0, 0.5 },
                                     { 0.5, 0.5, 0.0 }, { 0.5, 0.5, 1.0 } };
            for (int i = 0; i < 6; ++i)
                for (int j = i + 1; j < 6; ++j) {
                    if (j / 2 == i / 2) continue;   // opposite faces: no edge
                    add(c[i][0], c[i][1], c[i][2], c[j][0], c[j][1], c[j][2]);
                }
            break;
        }
        case LatticeFamily::Honeycomb:  honeycomb(m_hcCustom ? m_hcAngle : 30.0, m_hcCustom ? m_hcRib : 1.0); break;
        case LatticeFamily::Reentrant:  honeycomb(m_hcCustom ? m_hcAngle : -30.0, m_hcCustom ? m_hcRib : 2.0); break;
        default:
            break;
    }
}

void Lattice::buildWaves()
{
    m_waves.clear();
    m_jitterWaves.clear();
    m_jitterNorm  = 1.0;
    m_directions  = 0;

    std::uniform_real_distribution<double> phase(0.0, 2.0 * M_PI);

    // Integer wave vectors (periodic in the cube by construction) with
    // kmin <= |k| <= kmax, one of each +-k pair, filtered by `admissible`.
    auto candidates = [&](double kmin, double kmax,
                          const std::function<bool(int,int,int)>& admissible) {
        std::vector<std::array<int,3>> cand;
        const int K = static_cast<int>(std::ceil(kmax));
        for (int kx = -K; kx <= K; ++kx)
            for (int ky = -K; ky <= K; ++ky)
                for (int kz = -K; kz <= K; ++kz) {
                    if (kx < 0 || (kx == 0 && (ky < 0 || (ky == 0 && kz <= 0)))) continue;
                    const double n = std::sqrt(double(kx * kx + ky * ky + kz * kz));
                    if (n < kmin || n > kmax) continue;
                    if (admissible && !admissible(kx, ky, kz)) continue;
                    cand.push_back({ kx, ky, kz });
                }
        return cand;
    };
    auto drawFrom = [&](const std::vector<std::array<int,3>>& cand, int count,
                        std::vector<Wave>& out, double decay) {
        if (cand.empty()) return;
        std::uniform_int_distribution<size_t> pick(0, cand.size() - 1);
        for (int i = 0; i < count; ++i) {
            const std::array<int,3> k = cand[pick(m_rng)];
            const double n = std::sqrt(double(k[0] * k[0] + k[1] * k[1] + k[2] * k[2]));
            out.push_back({ double(k[0]), double(k[1]), double(k[2]), phase(m_rng),
                            decay > 0.0 ? std::pow(n, -decay) : 1.0 });
        }
    };

    if (m_family == LatticeFamily::Spinodoid) {
        // Kumar, Tan, Zheng & Kochmann (2020): wave directions drawn from the
        // union of cones of half-angle theta_i about the axes; a closed cone
        // (theta = 0) contributes nothing, 90 degrees is the whole sphere.
        const double cx = std::cos(m_theta[0] * M_PI / 180.0);
        const double cy = std::cos(m_theta[1] * M_PI / 180.0);
        const double cz = std::cos(m_theta[2] * M_PI / 180.0);
        auto inCones = [&](int kx, int ky, int kz) {
            const double n = std::sqrt(double(kx * kx + ky * ky + kz * kz));
            const double ax = std::abs(kx) / n, ay = std::abs(ky) / n, az = std::abs(kz) / n;
            return (m_theta[0] > 0.0 && ax >= cx - 1e-12)
                || (m_theta[1] > 0.0 && ay >= cy - 1e-12)
                || (m_theta[2] > 0.0 && az >= cz - 1e-12);
        };
        // Waves per cube edge ~ cells per edge, i.e. one "cell" per wavelength.
        const double beta = static_cast<double>(m_cells);
        std::vector<std::array<int,3>> cand = candidates(0.7 * beta, 1.3 * beta, inCones);
        if (cand.size() < 5) cand = candidates(0.5 * beta, 2.0 * beta, inCones);
        m_directions = cand.size();
        drawFrom(cand, 40, m_waves, 0.0);
        if (m_directions < 3)
            qWarning().noquote()
                << QString("[Lattice] only %1 admissible wave direction(s) for the spinodoid; "
                           "raise cells_per_edge or open the cones")
                       .arg(m_directions);
    }

    if (m_family == LatticeFamily::FourierSheet || m_family == LatticeFamily::FourierSkeletal) {
        bool loaded = false;
        if (!m_fourierFile.isEmpty()) {
            loaded = loadFourierFile(m_fourierFile);
            if (!loaded)
                qWarning().noquote()
                    << QString("[Lattice] could not read Fourier terms from \"%1\"; "
                               "drawing random terms from seed %2 instead")
                           .arg(m_fourierFile).arg(Parameters::seed);
        }
        if (!loaded) {
            std::vector<std::array<int,3>> cand = candidates(m_fourierKmin, m_fourierKmax, nullptr);
            m_directions = cand.size();
            // Distinct wave vectors when there are enough, so two draws never
            // collapse onto one; shuffle and take the first `terms`.
            if (static_cast<int>(cand.size()) >= m_fourierTerms) {
                std::shuffle(cand.begin(), cand.end(), m_rng);
                cand.resize(static_cast<size_t>(m_fourierTerms));
                std::uniform_real_distribution<double> jit(0.5, 1.5);
                for (const std::array<int,3>& k : cand) {
                    const double n = std::sqrt(double(k[0] * k[0] + k[1] * k[1] + k[2] * k[2]));
                    const double a = (m_fourierDecay > 0.0 ? std::pow(n, -m_fourierDecay) : 1.0) * jit(m_rng);
                    m_waves.push_back({ double(k[0]), double(k[1]), double(k[2]), phase(m_rng), a });
                }
            } else {
                drawFrom(cand, m_fourierTerms, m_waves, m_fourierDecay);
            }
        }
        // Cubic symmetry: each wave stands for its whole orbit under the 48
        // symmetries of the cube. Applied to file terms too: the file then
        // lists the generators.
        if (m_cubicSym) symmetrizeWaves();
        if (!loaded) {
            // Unit variance, so the level c means the same thing for every
            // draw. Terms from a file are kept exactly as given: a uniform
            // scale changes c, not the geometry, and the file is the record.
            double var = 0.0;
            for (const Wave& w : m_waves) var += 0.5 * w.amp * w.amp;
            if (var > 0.0) {
                const double s = 1.0 / std::sqrt(var);
                for (Wave& w : m_waves) w.amp *= s;
            }
        }
    }

    if (m_jitter > 0.0)
        drawFrom(candidates(1.0, 2.0 * m_cells, nullptr), 12, m_jitterWaves, 0.0);
}

// Every wave k -> the distinct images P S k over the 6 axis permutations P
// and 8 sign patterns S, with the wave's amplitude and phase. Because the
// cubic group is closed under inversion, the orbit sum is invariant under
// every element of the group for any phase, so the field has full cubic
// symmetry and the homogenized stiffness is cubic (Ex = Ey = Ez).
void Lattice::symmetrizeWaves()
{
    static const int perms[6][3] = { {0,1,2}, {0,2,1}, {1,0,2}, {1,2,0}, {2,0,1}, {2,1,0} };
    std::vector<Wave> out;
    for (const Wave& w : m_waves) {
        const double k[3] = { w.kx, w.ky, w.kz };
        std::vector<std::array<double,3>> seen;
        for (const int* p : perms)
            for (int s = 0; s < 8; ++s) {
                const std::array<double,3> q = { (s & 1 ? -1.0 : 1.0) * k[p[0]],
                                                 (s & 2 ? -1.0 : 1.0) * k[p[1]],
                                                 (s & 4 ? -1.0 : 1.0) * k[p[2]] };
                bool dup = false;
                for (const std::array<double,3>& r : seen)
                    if (std::abs(r[0] - q[0]) < 1e-9 && std::abs(r[1] - q[1]) < 1e-9 && std::abs(r[2] - q[2]) < 1e-9) { dup = true; break; }
                if (dup) continue;
                seen.push_back(q);
                out.push_back({ q[0], q[1], q[2], w.phase, w.amp });
            }
    }
    m_waves.swap(out);
}

// Smoothed noise: Gaussian white noise on the fixed kNoiseGrid^3 grid, blurred
// by a periodic separable Gaussian of sigma = noise_smooth * kNoiseGrid voxels,
// then scaled to unit variance so the level c means the same thing for every
// draw. The cube reads it through noiseAt(), whatever its own size.
void Lattice::buildNoise()
{
    m_noise.clear();
    if (m_family != LatticeFamily::NoiseSheet && m_family != LatticeFamily::NoiseSkeletal) return;

    const int N = kNoiseGrid;
    const std::size_t M = static_cast<std::size_t>(N) * N * N;
    std::vector<float> a(M), b(M);
    std::normal_distribution<double> gauss(0.0, 1.0);
    for (std::size_t i = 0; i < M; ++i) a[i] = static_cast<float>(gauss(m_rng));

    m_noiseSigmaVox = m_noiseSmooth * N;
    b.clear(); b.shrink_to_fit();
    periodicBlur(a, N, m_noiseSigmaVox);

    double mean = 0.0, var = 0.0;
    for (float v : a) mean += v;
    mean /= static_cast<double>(M);
    for (float v : a) var += (v - mean) * (v - mean);
    var /= static_cast<double>(M);
    const float scale = static_cast<float>(1.0 / std::sqrt(std::max(var, 1e-30)));
    for (float& v : a) v = (v - static_cast<float>(mean)) * scale;
    m_noise = std::move(a);
}

// Catmull-Rom weights are (0, 1, 0, 0) at t = 0, so a point on a node -- every
// voxel centre of a 64^3 cube -- reads the node value exactly (as the nearest-
// voxel lookup did when the noise lived on the cube's grid), and the zero
// taps are skipped there.
double Lattice::noiseAt(double X, double Y, double Z) const
{
    const int G = kNoiseGrid;
    const double P[3] = { X, Y, Z };
    int    i0[3];
    double w[3][4];
    for (int a = 0; a < 3; ++a) {
        const double u = P[a] * G - 0.5;
        const double f = std::floor(u);
        const double t = u - f, t2 = t * t, t3 = t2 * t;
        i0[a] = static_cast<int>(f) - 1;
        w[a][0] = 0.5 * (-t3 + 2.0 * t2 - t);
        w[a][1] = 0.5 * (3.0 * t3 - 5.0 * t2 + 2.0);
        w[a][2] = 0.5 * (-3.0 * t3 + 4.0 * t2 + t);
        w[a][3] = 0.5 * (t3 - t2);
    }
    auto wrapi = [G](int i) { return (i % G + G) % G; };
    double v = 0.0;
    for (int a = 0; a < 4; ++a) {
        if (w[0][a] == 0.0) continue;
        const std::size_t ix = static_cast<std::size_t>(wrapi(i0[0] + a));
        for (int b = 0; b < 4; ++b) {
            if (w[1][b] == 0.0) continue;
            const std::size_t iy = static_cast<std::size_t>(wrapi(i0[1] + b));
            double row = 0.0;
            for (int c = 0; c < 4; ++c) {
                if (w[2][c] == 0.0) continue;
                row += w[2][c] * m_noise[(ix * G + iy) * G + static_cast<std::size_t>(wrapi(i0[2] + c))];
            }
            v += w[0][a] * w[1][b] * row;
        }
    }
    return v;
}

void Lattice::periodicBlur(std::vector<float>& a, int N, double sigmaVox)
{
    if (sigmaVox <= 0.0) return;
    const int K = std::max(1, static_cast<int>(std::ceil(3.0 * sigmaVox)));
    std::vector<float> w(2 * K + 1);
    double wsum = 0.0;
    for (int d = -K; d <= K; ++d) { w[d + K] = static_cast<float>(std::exp(-0.5 * d * d / (sigmaVox * sigmaVox))); wsum += w[d + K]; }
    for (float& v : w) v = static_cast<float>(v / wsum);

    std::vector<float> b(a.size());
    auto idx = [N](int x, int y, int z) { return (static_cast<std::size_t>(x) * N + y) * N + z; };
    auto wrapi = [N](int i) { return (i % N + N) % N; };
    // Three periodic 1-D passes; axis 0 = x, 1 = y, 2 = z.
    for (int axis = 0; axis < 3; ++axis) {
        #pragma omp parallel for collapse(2) schedule(static)
        for (int p = 0; p < N; ++p)
            for (int q = 0; q < N; ++q)
                for (int i = 0; i < N; ++i) {
                    double acc = 0.0;
                    for (int d = -K; d <= K; ++d) {
                        const int j = wrapi(i + d);
                        const std::size_t src = axis == 0 ? idx(j, p, q) : axis == 1 ? idx(p, j, q) : idx(p, q, j);
                        acc += w[d + K] * a[src];
                    }
                    const std::size_t dst = axis == 0 ? idx(i, p, q) : axis == 1 ? idx(p, i, q) : idx(p, q, i);
                    b[dst] = static_cast<float>(acc);
                }
        std::swap(a, b);
    }
}

// `lattice_smooth`: the complete field (family, union, carving, grading,
// jitter) on the full grid, carved-out voxels set to the largest finite
// value so they stay void, blurred with a periodic Gaussian of sigma
// `lattice_smooth` cell edges. fieldAt() then reads this grid, so the level
// is solved and the cube rasterized on the rounded field.
void Lattice::buildSmoothed()
{
    m_smoothed.clear();
    if (m_smooth <= 0.0) return;
    const int N = numCubes;
    const std::size_t M = static_cast<std::size_t>(N) * N * N;
    std::vector<float> a(M);
    double finiteMax = -1e300;
    #pragma omp parallel for collapse(3) schedule(static) reduction(max:finiteMax)
    for (int x = 0; x < N; ++x)
        for (int y = 0; y < N; ++y)
            for (int z = 0; z < N; ++z) {
                const double v = fieldAt(x + 0.5, y + 0.5, z + 0.5);
                a[(static_cast<std::size_t>(x) * N + y) * N + z] = static_cast<float>(std::min(v, 1e30));
                if (v < 1e100 && v > finiteMax) finiteMax = v;
            }
    const float cap = static_cast<float>(finiteMax > -1e300 ? finiteMax : 0.0);
    for (float& v : a) if (v > 1e29f) v = cap;
    periodicBlur(a, N, m_smooth * N / m_cells);
    m_smoothed = std::move(a);
}

// One term per line: kx ky kz amplitude phase. Blank lines and lines starting
// with '#' are skipped; wave vectors must be integers so the field stays
// periodic in the cube.
bool Lattice::loadFourierFile(const QString& path)
{
    QFile f(path);
    if (!f.open(QIODevice::ReadOnly | QIODevice::Text)) return false;
    std::vector<Wave> terms;
    int lineNo = 0;
    while (!f.atEnd()) {
        ++lineNo;
        const QString line = QString::fromUtf8(f.readLine()).trimmed();
        if (line.isEmpty() || line.startsWith('#')) continue;
        const QStringList parts = line.split(QRegularExpression("[\\s,;]+"), Qt::SkipEmptyParts);
        if (parts.size() < 5) {
            qWarning().noquote() << QString("[Lattice] %1:%2: expected kx ky kz amplitude phase").arg(path).arg(lineNo);
            return false;
        }
        bool ok[5];
        const int    kx = parts[0].toInt(&ok[0]);
        const int    ky = parts[1].toInt(&ok[1]);
        const int    kz = parts[2].toInt(&ok[2]);
        const double a  = parts[3].toDouble(&ok[3]);
        const double ph = parts[4].toDouble(&ok[4]);
        if (!(ok[0] && ok[1] && ok[2] && ok[3] && ok[4])) {
            qWarning().noquote() << QString("[Lattice] %1:%2: could not parse \"%3\"").arg(path).arg(lineNo).arg(line);
            return false;
        }
        if (kx == 0 && ky == 0 && kz == 0) continue;   // a constant only shifts c
        terms.push_back({ double(kx), double(ky), double(kz), ph, a });
    }
    if (terms.empty()) return false;
    m_waves = std::move(terms);
    m_directions = m_waves.size();
    return true;
}

// The waves actually used, for the HDF5 metadata: this is the geometry
// vector a property-to-geometry network would output.
void Lattice::publishWaves()
{
    Parameters::lattice_wave_terms.clear();
    if (m_family == LatticeFamily::Spinodoid ||
        m_family == LatticeFamily::FourierSheet || m_family == LatticeFamily::FourierSkeletal) {
        Parameters::lattice_wave_terms.reserve(m_waves.size());
        for (const Wave& w : m_waves)
            Parameters::lattice_wave_terms.push_back({ float(w.kx), float(w.ky), float(w.kz),
                                                       float(w.amp), float(w.phase) });
        return;
    }
    // The TPMS level sets are finite Fourier series too, so publish them in
    // the same representation (k per cube edge = cells * unit vector):
    //   gyroid    = 1/2 [sin(x+y) + sin(x-y) + sin(y+z) + sin(y-z) + sin(z+x) + sin(z-x)]
    //   Schwarz P = cos x + cos y + cos z
    //   Schwarz D = 1/2 [sin(x+y+z) + sin(x+y-z) + sin(x-y+z) + sin(-x+y+z)]
    //   IWP       = sum over the six (1,1,0)-type pairs of cos - [cos 2x + cos 2y + cos 2z]
    // with sin t = cos(t - pi/2) and -cos t = cos(t + pi).
    for (const Wave& w : tpmsWaves())
        Parameters::lattice_wave_terms.push_back({ float(w.kx), float(w.ky), float(w.kz),
                                                   float(w.amp), float(w.phase) });
}

std::vector<Lattice::Wave> Lattice::tpmsWaves() const
{
    std::vector<Wave> out;
    const double c = static_cast<double>(m_cells);
    const double s = -M_PI / 2.0;   // sin -> cos phase
    auto add = [&](double kx, double ky, double kz, double amp, double phase) {
        out.push_back({ kx * c, ky * c, kz * c, phase, amp });
    };
    switch (m_family) {
        case LatticeFamily::GyroidSheet:
        case LatticeFamily::GyroidSkeletal:
            add( 1, 1, 0, 0.5, s); add( 1,-1, 0, 0.5, s);
            add( 0, 1, 1, 0.5, s); add( 0, 1,-1, 0.5, s);
            add( 1, 0, 1, 0.5, s); add(-1, 0, 1, 0.5, s);
            break;
        case LatticeFamily::SchwarzPSheet:
        case LatticeFamily::SchwarzPSkeletal:
            add(1, 0, 0, 1.0, 0.0); add(0, 1, 0, 1.0, 0.0); add(0, 0, 1, 1.0, 0.0);
            break;
        case LatticeFamily::SchwarzDSheet:
        case LatticeFamily::SchwarzDSkeletal:
            add( 1, 1, 1, 0.5, s); add( 1, 1,-1, 0.5, s);
            add( 1,-1, 1, 0.5, s); add(-1, 1, 1, 0.5, s);
            break;
        case LatticeFamily::IWPSheet:
        case LatticeFamily::IWPSkeletal:
            add( 1, 1, 0, 1.0, 0.0); add( 1,-1, 0, 1.0, 0.0);
            add( 0, 1, 1, 1.0, 0.0); add( 0, 1,-1, 1.0, 0.0);
            add( 1, 0, 1, 1.0, 0.0); add(-1, 0, 1, 1.0, 0.0);
            add( 2, 0, 0, 1.0, M_PI); add( 0, 2, 0, 1.0, M_PI); add( 0, 0, 2, 1.0, M_PI);
            break;
        case LatticeFamily::NeoviusSheet:
        case LatticeFamily::FischerKochSheet:
        case LatticeFamily::LidinoidSheet:      // the Lidinoid's constant term is a zero vector
            for (const cellforms::Wave& w : surfaceWaves(m_family)) add(w.k[0], w.k[1], w.k[2], w.amp, w.phase);
            break;
        default:
            break;
    }
    return out;
}

