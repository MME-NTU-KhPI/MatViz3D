bool Lattice::isSheet(LatticeFamily fam) const
{
    switch (fam) {
        case LatticeFamily::GyroidSheet: case LatticeFamily::SchwarzPSheet:
        case LatticeFamily::SchwarzDSheet: case LatticeFamily::IWPSheet:
        case LatticeFamily::FourierSheet:
        case LatticeFamily::NeoviusSheet: case LatticeFamily::FischerKochSheet: case LatticeFamily::LidinoidSheet:
            return true;
        default:
            return false;
    }
}

// f and grad f (derivatives with respect to the cube-fraction coordinates)
// for the level-set families. |f| / |grad f| is the first-order distance to
// the surface f = 0, which makes a sheet of (nearly) uniform thickness.
bool Lattice::levelSet(LatticeFamily fam, double X, double Y, double Z, double& f, double g[3]) const
{
    const double a = 2.0 * M_PI * m_cells;
    const double x = a * X, y = a * Y, z = a * Z;
    const double sx = std::sin(x), cx = std::cos(x);
    const double sy = std::sin(y), cy = std::cos(y);
    const double sz = std::sin(z), cz = std::cos(z);
    switch (fam) {
        case LatticeFamily::GyroidSheet:
        case LatticeFamily::GyroidSkeletal:
            f = sx * cy + sy * cz + sz * cx;
            g[0] = a * (cx * cy - sz * sx);
            g[1] = a * (-sx * sy + cy * cz);
            g[2] = a * (-sy * sz + cz * cx);
            return true;
        case LatticeFamily::SchwarzPSheet:
        case LatticeFamily::SchwarzPSkeletal:
            f = cx + cy + cz;
            g[0] = -a * sx; g[1] = -a * sy; g[2] = -a * sz;
            return true;
        case LatticeFamily::SchwarzDSheet:
        case LatticeFamily::SchwarzDSkeletal:
            f = sx * sy * sz + sx * cy * cz + cx * sy * cz + cx * cy * sz;
            g[0] = a * (cx * sy * sz + cx * cy * cz - sx * sy * cz - sx * cy * sz);
            g[1] = a * (sx * cy * sz - sx * sy * cz + cx * cy * cz - cx * sy * sz);
            g[2] = a * (sx * sy * cz - sx * cy * sz - cx * sy * sz + cx * cy * cz);
            return true;
        case LatticeFamily::IWPSheet:
        case LatticeFamily::IWPSkeletal:
            f = 2.0 * (cx * cy + cy * cz + cz * cx) - (std::cos(2 * x) + std::cos(2 * y) + std::cos(2 * z));
            g[0] = a * (-2.0 * sx * (cy + cz) + 2.0 * std::sin(2 * x));
            g[1] = a * (-2.0 * sy * (cx + cz) + 2.0 * std::sin(2 * y));
            g[2] = a * (-2.0 * sz * (cx + cy) + 2.0 * std::sin(2 * z));
            return true;
        case LatticeFamily::NeoviusSheet:
        case LatticeFamily::FischerKochSheet:
        case LatticeFamily::LidinoidSheet: {
            f = 0.0; g[0] = g[1] = g[2] = 0.0;
            for (const cellforms::Wave& w : surfaceWaves(fam)) {
                const double ph = a * (w.k[0] * X + w.k[1] * Y + w.k[2] * Z) + w.phase;
                f += w.amp * std::cos(ph);
                const double d = -w.amp * a * std::sin(ph);
                g[0] += d * w.k[0]; g[1] += d * w.k[1]; g[2] += d * w.k[2];
            }
            return true;
        }
        case LatticeFamily::FourierSheet:
        case LatticeFamily::FourierSkeletal: {
            f = 0.0; g[0] = g[1] = g[2] = 0.0;
            for (const Wave& w : m_waves) {
                const double ph = 2.0 * M_PI * (w.kx * X + w.ky * Y + w.kz * Z) + w.phase;
                f += w.amp * std::cos(ph);
                const double d = -w.amp * 2.0 * M_PI * std::sin(ph);
                g[0] += d * w.kx; g[1] += d * w.ky; g[2] += d * w.kz;
            }
            return true;
        }
        default:
            return false;
    }
}

double Lattice::rawField(double X, double Y, double Z) const
{
    double F = familyField(m_family, X, Y, Z);
    if (m_hasUnion) F = std::min(F, familyField(m_union, X, Y, Z));
    // Carving: inside {F2 <= s} the solid is gone whatever the level, so the
    // field is +inf there and the density is solved on what remains.
    if (m_hasSubtract && familyField(m_subtract, X, Y, Z) <= m_subtractSize) return 1e300;
    return F;
}

double Lattice::familyField(LatticeFamily fam, double X, double Y, double Z) const
{
    if (m_uniformWall && isSheet(fam)) {
        double f, g[3];
        levelSet(fam, X, Y, Z, f, g);
        if (m_metricOn)                            // first-order distance in the metric: |f| / |grad f| in the inverse metric
            for (int i = 0; i < 3; ++i) g[i] /= m_metric[i];
        const double gn = std::sqrt(g[0] * g[0] + g[1] * g[1] + g[2] * g[2]);
        // At a critical point on the surface (f = 0, grad f = 0) the ratio is
        // 0/0: that point is on the surface, so it is solid.
        return std::abs(f) / std::max(gn, 1e-12);
    }
    const bool sgn = latticeFamilyInfo(fam).signedLevelSet;
    switch (fam) {
        case LatticeFamily::GyroidSheet:
        case LatticeFamily::GyroidSkeletal: {
            const double a = 2.0 * M_PI * m_cells;
            const double f = gyroidF(a * X, a * Y, a * Z);
            return sgn ? f : std::abs(f);
        }
        case LatticeFamily::SchwarzPSheet:
        case LatticeFamily::SchwarzPSkeletal: {
            const double a = 2.0 * M_PI * m_cells;
            const double f = schwarzPF(a * X, a * Y, a * Z);
            return sgn ? f : std::abs(f);
        }
        case LatticeFamily::SchwarzDSheet:
        case LatticeFamily::SchwarzDSkeletal: {
            const double a = 2.0 * M_PI * m_cells;
            const double f = schwarzDF(a * X, a * Y, a * Z);
            return sgn ? f : std::abs(f);
        }
        case LatticeFamily::IWPSheet:
        case LatticeFamily::IWPSkeletal: {
            const double a = 2.0 * M_PI * m_cells;
            const double f = iwpF(a * X, a * Y, a * Z);
            return sgn ? f : std::abs(f);
        }
        case LatticeFamily::SimpleCubic:
        case LatticeFamily::BCC:
        case LatticeFamily::FCC:
        case LatticeFamily::Octet: {
            const double u = wrap01(X * m_cells);
            const double v = wrap01(Y * m_cells);
            const double w = wrap01(Z * m_cells);
            double best = 1e300;
            if (m_metricOn) {                      // the distance in the metric = the plain distance after scaling every axis
                const double mx = m_metric[0], my = m_metric[1], mz = m_metric[2];
                for (const Segment& s : m_segments)
                    for (int ox = -1; ox <= 1; ++ox)
                        for (int oy = -1; oy <= 1; ++oy)
                            for (int oz = -1; oz <= 1; ++oz) {
                                const double d = segmentDistance(mx * (u + ox), my * (v + oy), mz * (w + oz),
                                                                 mx * s.ax, my * s.ay, mz * s.az, mx * s.bx, my * s.by, mz * s.bz);
                                if (d < best) best = d;
                            }
                return std::round(best * 1e9) / 1e9;
            }
            for (const Segment& s : m_segments)
                for (int ox = -1; ox <= 1; ++ox)
                    for (int oy = -1; oy <= 1; ++oy)
                        for (int oz = -1; oz <= 1; ++oz) {
                            const double d = segmentDistance(u + ox, v + oy, w + oz,
                                                             s.ax, s.ay, s.az, s.bx, s.by, s.bz);
                            if (d < best) best = d;
                        }
            // Snap away rounding noise so the voxel shells around a strut tie
            // exactly in the quantile solve (see plateField).
            return std::round(best * 1e9) / 1e9;
        }
        case LatticeFamily::Honeycomb:
        case LatticeFamily::Reentrant: {
            double u = X * m_cells  * m_hcW;
            double v = Y * m_cellsY * m_hcP;
            u -= m_hcW * std::floor(u / m_hcW);
            v -= m_hcP * std::floor(v / m_hcP);
            double best = 1e300;
            for (const Segment& s : m_segments)
                for (int ox = -1; ox <= 1; ++ox)
                    for (int oy = -1; oy <= 1; ++oy) {
                        const double d = segmentDistance(u + ox * m_hcW, v + oy * m_hcP, 0.0,
                                                         s.ax, s.ay, 0.0, s.bx, s.by, 0.0);
                        if (d < best) best = d;
                    }
            return std::round(best * 1e9) / 1e9;   // exact ties for axis-aligned walls
        }
        case LatticeFamily::Spinodoid: {
            if (m_waves.empty()) return 0.0;
            const double amp = std::sqrt(2.0 / static_cast<double>(m_waves.size()));
            double g = 0.0;
            for (const Wave& w : m_waves)
                g += std::cos(2.0 * M_PI * (w.kx * X + w.ky * Y + w.kz * Z) + w.phase);
            return amp * g;
        }
        case LatticeFamily::FourierSheet:
        case LatticeFamily::FourierSkeletal: {
            double f = 0.0;
            for (const Wave& w : m_waves)
                f += w.amp * std::cos(2.0 * M_PI * (w.kx * X + w.ky * Y + w.kz * Z) + w.phase);
            return sgn ? f : std::abs(f);
        }
        case LatticeFamily::NoiseSheet:
        case LatticeFamily::NoiseSkeletal: {
            if (m_noise.empty()) return 0.0;
            const double v = noiseAt(X, Y, Z);
            return sgn ? v : std::abs(v);
        }
        case LatticeFamily::PlateSC: case LatticeFamily::PlateBCC: case LatticeFamily::PlateFCC:
        case LatticeFamily::PlateSCBCC: case LatticeFamily::PlateSCFCC: case LatticeFamily::PlateBCCFCC:
        case LatticeFamily::PlateSCBCCFCC:
            return plateField(fam, X, Y, Z);
        case LatticeFamily::SpheresSC: case LatticeFamily::SpheresBCC: case LatticeFamily::SpheresFCC:
        case LatticeFamily::CylindersAxes:
            return siteField(fam, X, Y, Z);
        case LatticeFamily::CubicAssembly:
            return assemblyField(X, Y, Z);
        case LatticeFamily::FoamKelvin: case LatticeFamily::FoamRhombic:
        case LatticeFamily::FoamWeairePhelan: case LatticeFamily::FoamRandom:
            return foamField(X, Y, Z);
        case LatticeFamily::Mycelium:
            return myceliumField(X, Y, Z);
        case LatticeFamily::NeoviusSheet: case LatticeFamily::FischerKochSheet: case LatticeFamily::LidinoidSheet: {
            double f, g[3];
            levelSet(fam, X, Y, Z, f, g);
            return std::abs(f);
        }
        case LatticeFamily::GlassSponge: case LatticeFamily::ChiralTwist: case LatticeFamily::Woven:
        case LatticeFamily::Bouligand: case LatticeFamily::DiamondBallStick: case LatticeFamily::Reentrant3D:
            return myceliumField(X, Y, Z);
        case LatticeFamily::Radiolarian: case LatticeFamily::TrabecularBone: case LatticeFamily::Wood:
        case LatticeFamily::Cuttlebone: case LatticeFamily::Turing: case LatticeFamily::HierarchicalGyroid:
            return m_formField.at(wrap01(X * m_cells), wrap01(Y * m_cells), wrap01(Z * m_cells));
    }
    return 0.0;
}

// Spheres: distance to the nearest lattice site (corners; + the centre for
// BCC; + the face centres for FCC), so c is the sphere radius in cell units.
// Cylinders: distance to the nearest of the three axis lines through the
// face centres, c the cylinder radius. Snapped like the plates so symmetric
// voxels tie exactly.
double Lattice::siteField(LatticeFamily fam, double X, double Y, double Z) const
{
    const double u[3] = { wrap01(X * m_cells), wrap01(Y * m_cells), wrap01(Z * m_cells) };
    auto wrapc = [](double v) { return v - std::round(v); };
    double best = 1e300;
    if (fam == LatticeFamily::CylindersAxes) {
        for (int i = 0; i < 3; ++i) {
            const int j = (i + 1) % 3, k = (i + 2) % 3;
            const double a = wrapc(u[j] - 0.5), b = wrapc(u[k] - 0.5);
            best = std::min(best, std::sqrt(a * a + b * b));
        }
    } else {
        static const double corner[1][3] = { {0, 0, 0} };
        static const double bcc[2][3]    = { {0, 0, 0}, {0.5, 0.5, 0.5} };
        static const double fcc[4][3]    = { {0, 0, 0}, {0.5, 0.5, 0}, {0.5, 0, 0.5}, {0, 0.5, 0.5} };
        const double (*sites)[3] = corner; int n = 1;
        if (fam == LatticeFamily::SpheresBCC) { sites = bcc; n = 2; }
        if (fam == LatticeFamily::SpheresFCC) { sites = fcc; n = 4; }
        for (int s = 0; s < n; ++s) {
            double d2 = 0.0;
            for (int i = 0; i < 3; ++i) { const double w = wrapc(u[i] - sites[s][i]); d2 += w * w; }
            best = std::min(best, std::sqrt(d2));
        }
    }
    return std::round(best * 1e9) / 1e9;
}

// ─────────────────────────────────────────────────────────────────────────────
//  Foams (3D honeycombs): walls, windows or edges of a Voronoi partition
// ─────────────────────────────────────────────────────────────────────────────

namespace {

using V3 = std::array<double,3>;
struct ClipFace { std::vector<V3> v; int id; };

inline double dotv(const V3& a, const double* n) { return a[0] * n[0] + a[1] * n[1] + a[2] * n[2]; }

// Area vector of a planar polygon (half the sum of cross products).
inline double polygonArea(const std::vector<V3>& v)
{
    double s[3] = { 0.0, 0.0, 0.0 };
    for (size_t k = 0; k < v.size(); ++k) {
        const V3& a = v[k]; const V3& b = v[(k + 1) % v.size()];
        s[0] += a[1] * b[2] - a[2] * b[1];
        s[1] += a[2] * b[0] - a[0] * b[2];
        s[2] += a[0] * b[1] - a[1] * b[0];
    }
    return 0.5 * std::sqrt(s[0] * s[0] + s[1] * s[1] + s[2] * s[2]);
}

// Cut the convex polyhedron (a list of face polygons) by the half-space
// n.x <= h and close it with the cap polygon, labelled `id`. Vertices on the
// plane count as inside and as cap points, so a plane through a vertex or an
// edge only (a redundant neighbour) leaves no cap.
void clipPolyhedron(std::vector<ClipFace>& faces, const double n[3], double h, int id)
{
    constexpr double eps = 1e-12;
    std::vector<V3> cut;
    std::vector<ClipFace> out;
    out.reserve(faces.size() + 1);
    for (const ClipFace& f : faces) {
        std::vector<V3> res;
        const size_t m = f.v.size();
        for (size_t k = 0; k < m; ++k) {
            const V3& a = f.v[k]; const V3& b = f.v[(k + 1) % m];
            const double sa = dotv(a, n) - h, sb = dotv(b, n) - h;
            if (sa <= eps) res.push_back(a);
            if (std::abs(sa) <= eps) cut.push_back(a);
            if ((sa < -eps && sb > eps) || (sa > eps && sb < -eps)) {
                const double t = sa / (sa - sb);
                const V3 q = { a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1]), a[2] + t * (b[2] - a[2]) };
                res.push_back(q);
                cut.push_back(q);
            }
        }
        if (res.size() >= 3 && polygonArea(res) > 1e-14) out.push_back({ std::move(res), f.id });
    }
    std::vector<V3> cap;
    for (const V3& q : cut) {
        bool dup = false;
        for (const V3& c : cap)
            if (std::abs(c[0] - q[0]) + std::abs(c[1] - q[1]) + std::abs(c[2] - q[2]) < 1e-10) { dup = true; break; }
        if (!dup) cap.push_back(q);
    }
    if (cap.size() >= 3) {
        V3 c = { 0.0, 0.0, 0.0 };
        for (const V3& q : cap) for (int i = 0; i < 3; ++i) c[i] += q[i] / static_cast<double>(cap.size());
        // In-plane basis e1, e2 = n x e1; order the cap points by angle.
        const double ax = std::abs(n[0]) < 0.9 ? 1.0 : 0.0, ay = 1.0 - ax;
        double e1[3] = { ay * n[2], -ax * n[2], ax * n[1] - ay * n[0] };
        const double l1 = std::sqrt(e1[0] * e1[0] + e1[1] * e1[1] + e1[2] * e1[2]);
        for (double& e : e1) e /= l1;
        const double e2[3] = { n[1] * e1[2] - n[2] * e1[1], n[2] * e1[0] - n[0] * e1[2], n[0] * e1[1] - n[1] * e1[0] };
        std::sort(cap.begin(), cap.end(), [&](const V3& p, const V3& q) {
            const double pa = std::atan2((p[0] - c[0]) * e2[0] + (p[1] - c[1]) * e2[1] + (p[2] - c[2]) * e2[2],
                                         (p[0] - c[0]) * e1[0] + (p[1] - c[1]) * e1[1] + (p[2] - c[2]) * e1[2]);
            const double qa = std::atan2((q[0] - c[0]) * e2[0] + (q[1] - c[1]) * e2[1] + (q[2] - c[2]) * e2[2],
                                         (q[0] - c[0]) * e1[0] + (q[1] - c[1]) * e1[1] + (q[2] - c[2]) * e1[2]);
            return pa < qa;
        });
        if (polygonArea(cap) > 1e-14) out.push_back({ std::move(cap), id });
    }
    faces.swap(out);
}

} // namespace

bool Lattice::loadFoamFile(const QString& path)
{
    QFile f(path);
    if (!f.open(QIODevice::ReadOnly | QIODevice::Text)) return false;
    std::vector<std::array<double,3>> sites;
    while (!f.atEnd()) {
        const QString line = QString::fromUtf8(f.readLine()).section('#', 0, 0).trimmed();
        if (line.isEmpty()) continue;
        const QStringList t = line.split(QRegularExpression("[\\s,;]+"), Qt::SkipEmptyParts);
        if (t.size() < 3) continue;
        bool ok[3];
        const double x = t[0].toDouble(&ok[0]), y = t[1].toDouble(&ok[1]), z = t[2].toDouble(&ok[2]);
        if (!ok[0] || !ok[1] || !ok[2]) continue;
        sites.push_back({ wrap01(x), wrap01(y), wrap01(z) });
    }
    if (sites.empty()) return false;
    m_foamSites = std::move(sites);
    return true;
}

void Lattice::buildFoam()
{
    m_foamSites.clear();
    m_foamImages.clear();
    m_foamImageSite.clear();
    m_foamCells.clear();
    Parameters::lattice_foam_sites.clear();
    m_hasFoam = true;
    if (isFoamFamily(m_family))                         m_foamFamily = m_family;
    else if (m_hasUnion && isFoamFamily(m_union))       m_foamFamily = m_union;
    else if (m_hasSubtract && isFoamFamily(m_subtract)) m_foamFamily = m_subtract;
    else { m_hasFoam = false; return; }

    switch (m_foamFamily) {
        case LatticeFamily::FoamKelvin:
            m_foamSites = { {0, 0, 0}, {0.5, 0.5, 0.5} };
            break;
        case LatticeFamily::FoamRhombic:
            m_foamSites = { {0, 0, 0}, {0.5, 0.5, 0}, {0.5, 0, 0.5}, {0, 0.5, 0.5} };
            break;
        case LatticeFamily::FoamWeairePhelan:   // A15 (Cr3Si): the cell centre and corner + two sites on every face
            m_foamSites = { {0, 0, 0}, {0.5, 0.5, 0.5},
                            {0.25, 0.5, 0}, {0.75, 0.5, 0}, {0, 0.25, 0.5}, {0, 0.75, 0.5}, {0.5, 0, 0.25}, {0.5, 0, 0.75} };
            break;
        default: {
            bool loaded = false;
            if (!m_foamFile.isEmpty()) {
                loaded = loadFoamFile(m_foamFile);
                if (!loaded)
                    qWarning().noquote() << QString("[Lattice] could not read foam sites from \"%1\"; drawing %2 from seed %3 instead")
                                                .arg(m_foamFile).arg(m_foamBubbles).arg(Parameters::seed);
            }
            if (!loaded) {
                // Random sequential addition with a hard core of 0.7 bubble sizes
                // (periodic distance): no sliver cells, so no dust-thin faces.
                // Coordinates are rounded to float, so the published table
                // rebuilds the cell bit for bit through foam_file.
                std::uniform_real_distribution<double> U(0.0, 1.0);
                const int n = m_foamBubbles;
                auto draw = [&]() { return wrap01(static_cast<double>(static_cast<float>(U(m_rng)))); };
                double dmin = 0.7 * std::cbrt(1.0 / n);
                for (;;) {
                    m_foamSites.clear();
                    for (int tries = 0; static_cast<int>(m_foamSites.size()) < n && tries < 2000 * n; ++tries) {
                        const std::array<double,3> q = { draw(), draw(), draw() };
                        bool clear = true;
                        for (const auto& s : m_foamSites) {
                            double d2 = 0.0;
                            for (int i = 0; i < 3; ++i) { const double w = q[i] - s[i] - std::round(q[i] - s[i]); d2 += w * w; }
                            if (d2 < dmin * dmin) { clear = false; break; }
                        }
                        if (clear) m_foamSites.push_back(q);
                    }
                    if (static_cast<int>(m_foamSites.size()) == n) break;
                    dmin *= 0.9;
                }
            }
            break;
        }
    }
    for (const auto& s : m_foamSites)
        Parameters::lattice_foam_sites.push_back({ static_cast<float>(s[0]), static_cast<float>(s[1]), static_cast<float>(s[2]) });
    const size_t ns = m_foamSites.size();
    m_foamBubble = std::cbrt(1.0 / static_cast<double>(ns));

    // Sites in the unit cell and in its 26 neighbours: the nearest site of any
    // point of the cell is among them (the covering radius is below 1).
    for (int ox = -1; ox <= 1; ++ox)
        for (int oy = -1; oy <= 1; ++oy)
            for (int oz = -1; oz <= 1; ++oz)
                for (size_t i = 0; i < ns; ++i) {
                    m_foamImages.push_back({ m_foamSites[i][0] + ox, m_foamSites[i][1] + oy, m_foamSites[i][2] + oz });
                    m_foamImageSite.push_back(static_cast<int>(i));
                }

    // Covering radius R (farthest a point can be from its site), from a grid
    // plus the grid's own half diagonal: every Voronoi neighbour of a site is
    // within 2R of it (their common face has a point within R of both).
    const int G = 24;
    double R = 0.0;
    for (int i = 0; i < G; ++i)
        for (int j = 0; j < G; ++j)
            for (int k = 0; k < G; ++k) {
                const double q[3] = { (i + 0.5) / G, (j + 0.5) / G, (k + 0.5) / G };
                double b = 1e300;
                for (const auto& s : m_foamImages) {
                    const double dx = q[0] - s[0], dy = q[1] - s[1], dz = q[2] - s[2];
                    b = std::min(b, dx * dx + dy * dy + dz * dz);
                }
                R = std::max(R, std::sqrt(b));
            }
    R += 0.5 * std::sqrt(3.0) / G;

    // Every cell: a box around the site cut by the bisector planes of all
    // sites within 2R (nearest first). Planes that leave no face are not
    // neighbours (e.g. the six second neighbours of FCC touch the rhombic
    // dodecahedron at its corners only).
    m_foamCells.resize(ns);
    for (size_t i = 0; i < ns; ++i) {
        const auto& p = m_foamSites[i];
        struct Cand { double n[3]; double half; int j; double D[3]; };
        std::vector<Cand> cand;
        for (int ox = -2; ox <= 2; ++ox)
            for (int oy = -2; oy <= 2; ++oy)
                for (int oz = -2; oz <= 2; ++oz)
                    for (size_t j = 0; j < ns; ++j) {
                        const double D[3] = { m_foamSites[j][0] + ox - p[0], m_foamSites[j][1] + oy - p[1], m_foamSites[j][2] + oz - p[2] };
                        const double L = std::sqrt(D[0] * D[0] + D[1] * D[1] + D[2] * D[2]);
                        if (L < 1e-12 || L > 2.0 * R + 1e-9) continue;
                        cand.push_back({ { D[0] / L, D[1] / L, D[2] / L }, 0.5 * L, static_cast<int>(j), { D[0], D[1], D[2] } });
                    }
        std::sort(cand.begin(), cand.end(), [](const Cand& a, const Cand& b) { return a.half < b.half; });

        const double H = 1.5 * R + 0.01;
        std::vector<ClipFace> poly = {
            { { {-H,-H,-H}, {-H, H,-H}, { H, H,-H}, { H,-H,-H} }, -1 },
            { { {-H,-H, H}, { H,-H, H}, { H, H, H}, {-H, H, H} }, -1 },
            { { {-H,-H,-H}, { H,-H,-H}, { H,-H, H}, {-H,-H, H} }, -1 },
            { { {-H, H,-H}, {-H, H, H}, { H, H, H}, { H, H,-H} }, -1 },
            { { {-H,-H,-H}, {-H,-H, H}, {-H, H, H}, {-H, H,-H} }, -1 },
            { { { H,-H,-H}, { H, H,-H}, { H, H, H}, { H,-H, H} }, -1 },
        };
        for (size_t c = 0; c < cand.size(); ++c)
            clipPolyhedron(poly, cand[c].n, cand[c].half, static_cast<int>(c));

        FoamCell& cell = m_foamCells[i];
        for (const ClipFace& f : poly) {
            if (f.id < 0) {
                qWarning() << "[Lattice] foam: a Voronoi cell is not closed by its neighbours; its walls may be wrong";
                continue;
            }
            FoamFace face;
            for (int k = 0; k < 3; ++k) face.n[k] = cand[static_cast<size_t>(f.id)].n[k];
            face.half = cand[static_cast<size_t>(f.id)].half;
            face.nb   = cand[static_cast<size_t>(f.id)].j;
            for (int k = 0; k < 3; ++k) face.off[k] = cand[static_cast<size_t>(f.id)].D[k];
            for (size_t k = 0; k < f.v.size(); ++k) {
                const V3& a = f.v[k]; const V3& b = f.v[(k + 1) % f.v.size()];
                if (std::abs(a[0] - b[0]) + std::abs(a[1] - b[1]) + std::abs(a[2] - b[2]) < 1e-9) continue;
                const std::array<double,6> e = { a[0], a[1], a[2], b[0], b[1], b[2] };
                face.edges.push_back(e);
                bool dup = false;   // each edge is shared by two faces of the cell
                for (const auto& g : cell.edges) {
                    const double same = std::abs(g[0] - e[0]) + std::abs(g[1] - e[1]) + std::abs(g[2] - e[2])
                                      + std::abs(g[3] - e[3]) + std::abs(g[4] - e[4]) + std::abs(g[5] - e[5]);
                    const double flip = std::abs(g[0] - e[3]) + std::abs(g[1] - e[4]) + std::abs(g[2] - e[5])
                                      + std::abs(g[3] - e[0]) + std::abs(g[4] - e[1]) + std::abs(g[5] - e[2]);
                    if (std::min(same, flip) < 1e-7) { dup = true; break; }
                }
                if (!dup) cell.edges.push_back(e);
            }
            cell.faces.push_back(std::move(face));
        }
    }

    // Struts of the open-cell mode: own edges + the edges of the face
    // neighbours that start at one of the cell's vertices (a 4-valent vertex
    // of the rhombic foam joins edges of six cells).
    auto sameEdge = [](const std::array<double,6>& g, const std::array<double,6>& e) {
        const double same = std::abs(g[0] - e[0]) + std::abs(g[1] - e[1]) + std::abs(g[2] - e[2])
                          + std::abs(g[3] - e[3]) + std::abs(g[4] - e[4]) + std::abs(g[5] - e[5]);
        const double flip = std::abs(g[0] - e[3]) + std::abs(g[1] - e[4]) + std::abs(g[2] - e[5])
                          + std::abs(g[3] - e[0]) + std::abs(g[4] - e[1]) + std::abs(g[5] - e[2]);
        return std::min(same, flip) < 1e-7;
    };
    for (FoamCell& cell : m_foamCells) {
        cell.struts = cell.edges;
        auto atVertex = [&](double x, double y, double z) {
            for (const auto& g : cell.edges)
                if (std::abs(g[0] - x) + std::abs(g[1] - y) + std::abs(g[2] - z) < 1e-7
                    || std::abs(g[3] - x) + std::abs(g[4] - y) + std::abs(g[5] - z) < 1e-7) return true;
            return false;
        };
        for (const FoamFace& f : cell.faces) {
            if (f.nb < 0) continue;
            for (const auto& g : m_foamCells[static_cast<size_t>(f.nb)].edges) {
                const std::array<double,6> e = { g[0] + f.off[0], g[1] + f.off[1], g[2] + f.off[2],
                                                 g[3] + f.off[0], g[4] + f.off[1], g[5] + f.off[2] };
                if (!atVertex(e[0], e[1], e[2]) && !atVertex(e[3], e[4], e[5])) continue;
                bool dup = false;
                for (const auto& h : cell.struts) if (sameEdge(h, e)) { dup = true; break; }
                if (!dup) cell.struts.push_back(e);
            }
        }
    }
}

// Walls: distance to the boundary of the point's own Voronoi cell, the
// nearest face plane (exact: the nearest wall of a point is a face of its own
// cell). Windows: max(d, e - w), d that distance, e the distance in the face
// plane to the face's edges (the foot of the perpendicular on the nearest face
// plane lies on that face), w = foam_frame bubble sizes: the wall is 2c thick
// and reaches c + w from the edges into the face, so a thicker wall also has a
// wider frame and any density is reachable; w = 0 leaves square struts along
// the edges, a large w closes the windows. Edges: distance to the nearest edge
// of the cell (or of a neighbour, at a vertex). Snapped like the plates so
// mirror-image voxels tie.
double Lattice::foamField(double X, double Y, double Z) const
{
    if (m_foamCells.empty()) return 1e300;
    const double u[3] = { wrap01(X * m_cells), wrap01(Y * m_cells), wrap01(Z * m_cells) };
    size_t nearest = 0;
    double bd = 1e300;
    for (size_t k = 0; k < m_foamImages.size(); ++k) {
        const auto& s = m_foamImages[k];
        const double dx = u[0] - s[0], dy = u[1] - s[1], dz = u[2] - s[2];
        const double d2 = dx * dx + dy * dy + dz * dz;
        if (d2 < bd) { bd = d2; nearest = k; }
    }
    const auto& P = m_foamImages[nearest];
    const FoamCell& cell = m_foamCells[static_cast<size_t>(m_foamImageSite[nearest])];
    const double v[3] = { u[0] - P[0], u[1] - P[1], u[2] - P[2] };

    double F = 1e300;
    if (m_foamMode == QLatin1String("edges")) {
        for (const auto& e : cell.struts)
            F = std::min(F, segmentDistance(v[0], v[1], v[2], e[0], e[1], e[2], e[3], e[4], e[5]));
    } else {
        const FoamFace* near = nullptr;
        for (const FoamFace& f : cell.faces) {
            const double d = f.half - (v[0] * f.n[0] + v[1] * f.n[1] + v[2] * f.n[2]);
            if (d < F) { F = d; near = &f; }
        }
        F = std::max(F, 0.0);
        if (near && m_foamMode == QLatin1String("windows")) {
            double e2 = 1e300;
            for (const auto& e : near->edges) {
                const double d = segmentDistance(v[0], v[1], v[2], e[0], e[1], e[2], e[3], e[4], e[5]);
                e2 = std::min(e2, d * d - F * F);
            }
            F = std::max(F, std::sqrt(std::max(e2, 0.0)) - m_foamFrame * m_foamBubble);
        }
    }
    return F < 1e300 ? std::round(F * 1e9) / 1e9 : F;
}

// ─────────────────────────────────────────────────────────────────────────────
//  Mycelium: a fungal colony grown in the unit cell (mycelium.h)
// ─────────────────────────────────────────────────────────────────────────────

// One piece of hypha per line: ax ay az bx by bz [weight], cell units, b the
// far end of the piece (not wrapped), weight 1 when left out. Blank lines and
// lines starting with '#' are skipped; a is moved into [0, 1)^3 with its piece.
bool Lattice::loadMyceliumFile(const QString& path)
{
    QFile f(path);
    if (!f.open(QIODevice::ReadOnly | QIODevice::Text)) return false;
    std::vector<mycelium::Segment> out;
    while (!f.atEnd()) {
        const QString line = QString::fromUtf8(f.readLine()).trimmed();
        if (line.isEmpty() || line.startsWith('#')) continue;
        const QStringList t = line.split(QRegularExpression("[\\s,;]+"), Qt::SkipEmptyParts);
        if (t.size() < 6) return false;
        double v[7] = { 0, 0, 0, 0, 0, 0, 1.0 };
        for (int i = 0; i < std::min<int>(7, t.size()); ++i) {
            bool ok = false;
            v[i] = t[i].toDouble(&ok);
            if (!ok || !std::isfinite(v[i])) return false;
        }
        if (v[6] <= 0.0) return false;
        mycelium::Segment s;
        for (int i = 0; i < 3; ++i) {
            const double sh = std::floor(v[i]);
            s.a[i] = static_cast<float>(v[i] - sh);
            s.b[i] = static_cast<float>(v[i + 3] - sh);
            if (s.a[i] >= 1.0f) { s.a[i] -= 1.0f; s.b[i] -= 1.0f; }
        }
        s.w = static_cast<float>(v[6]);
        out.push_back(s);
    }
    if (out.empty()) return false;
    m_mycSegments = std::move(out);
    return true;
}

void Lattice::buildMycelium()
{
    m_mycSegments.clear();
    m_mycStart.clear();
    m_mycIndex.clear();
    m_mycStats = mycelium::Stats();
    m_mycMinWeight = 1.0;
    Parameters::lattice_mycelium_segments.clear();
    Parameters::lattice_mycelium_stats = mycelium::Stats();
    if (!usesPieceTable()) return;

    // The segment forms (cellforms.h) share the piece table and its bucket grid;
    // their pieces follow from the knobs, so they are not published.
    const bool grown = m_family == LatticeFamily::Mycelium;
    if (grown) {
        bool loaded = false;
        if (!m_mycFile.isEmpty()) {
            loaded = loadMyceliumFile(m_mycFile);
            if (!loaded)
                qWarning().noquote() << QString("[Lattice] could not read mycelium pieces from \"%1\"; growing from seed %2 instead")
                                            .arg(m_mycFile).arg(Parameters::seed);
        }
        if (loaded) m_mycStats = mycelium::measure(m_mycSegments);
        else        m_mycSegments = mycelium::grow(m_myc, m_rng, &m_mycStats);
    } else {
        m_mycSegments = cellforms::segments(static_cast<cellforms::Kind>(formIndex(m_family)), m_formKnobs);
    }
    if (m_mycSegments.empty()) {
        qWarning() << "[Lattice] the piece table is empty; the cell is empty";
        return;
    }

    double wmin = 1e300, sumW2L = 0.0;
    if (grown) Parameters::lattice_mycelium_segments.reserve(m_mycSegments.size());
    for (const mycelium::Segment& s : m_mycSegments) {
        if (grown) Parameters::lattice_mycelium_segments.push_back({ s.a[0], s.a[1], s.a[2], s.b[0], s.b[1], s.b[2], s.w });
        double L2 = 0.0;
        for (int i = 0; i < 3; ++i) { const double d = double(s.b[i]) - double(s.a[i]); L2 += d * d; }
        wmin = std::min(wmin, double(s.w));
        sumW2L += double(s.w) * double(s.w) * std::sqrt(L2);
    }
    m_mycMinWeight = wmin;
    if (grown) Parameters::lattice_mycelium_stats = m_mycStats;

    // Cut-off: 2.5 x the radius the pieces' own volume would need for the
    // density (their overlaps make the real one larger); Initialization()
    // widens it if the solved level gets close.
    const double cEst = sumW2L > 0.0 ? std::sqrt(m_target / (M_PI * sumW2L)) : 0.1;
    m_mycCut = std::clamp(2.5 * cEst, 0.03, 0.5);
    buildMyceliumGrid();
}

bool Lattice::usesPieceTable() const
{
    return m_family == LatticeFamily::Mycelium
        || (isFormFamily(m_family) && cellforms::isSegmentKind(static_cast<cellforms::Kind>(formIndex(m_family))));
}

// The field forms; the segment forms build their piece table in buildMycelium().
void Lattice::buildForm()
{
    m_formField.clear();
    if (!isFormFamily(m_family) || usesPieceTable()) return;
    m_formField.build(static_cast<cellforms::Kind>(formIndex(m_family)), m_formKnobs, m_rng);
}

// Bucket b of a G^3 grid over the cell lists every piece that comes within
// R = cut x the largest weight of it; a point then only looks at its own
// bucket, and every value below the cut is exact.
void Lattice::buildMyceliumGrid()
{
    double wmax = 0.0;
    for (const mycelium::Segment& s : m_mycSegments) wmax = std::max(wmax, double(s.w));
    const double R = m_mycCut * std::max(wmax, 1e-6);
    const int G = std::clamp(static_cast<int>(std::floor(2.0 / R)), 1, 96);
    m_mycG = G;
    const size_t nb = static_cast<size_t>(G) * G * G;
    auto wrapG = [G](int i) { return ((i % G) + G) % G; };
    auto range = [&](const mycelium::Segment& s, int a, int& lo, int& hi) {
        const double l = std::min(s.a[a], s.b[a]) - R, h = std::max(s.a[a], s.b[a]) + R;
        lo = static_cast<int>(std::floor(l * G));
        hi = static_cast<int>(std::floor(h * G));
        if (hi - lo + 1 >= G) { lo = 0; hi = G - 1; }
    };
    std::vector<int> count(nb + 1, 0);
    for (int pass = 0; pass < 2; ++pass) {
        std::vector<int> fill;
        if (pass == 1) {
            for (size_t b = 0; b < nb; ++b) count[b + 1] += count[b];
            m_mycStart = count;
            m_mycIndex.assign(static_cast<size_t>(count[nb]), 0);
            fill.assign(m_mycStart.begin(), m_mycStart.end() - 1);
        }
        for (size_t k = 0; k < m_mycSegments.size(); ++k) {
            int lo[3], hi[3];
            for (int a = 0; a < 3; ++a) range(m_mycSegments[k], a, lo[a], hi[a]);
            for (int i = lo[0]; i <= hi[0]; ++i)
                for (int j = lo[1]; j <= hi[1]; ++j)
                    for (int l = lo[2]; l <= hi[2]; ++l) {
                        const size_t b = (static_cast<size_t>(wrapG(i)) * G + wrapG(j)) * G + wrapG(l);
                        if (pass == 0) ++count[b + 1];
                        else           m_mycIndex[static_cast<size_t>(fill[b]++)] = static_cast<int>(k);
                    }
        }
    }
}

double Lattice::myceliumField(double X, double Y, double Z) const
{
    if (m_mycStart.empty()) return 1e300;
    const double u[3] = { wrap01(X * m_cells), wrap01(Y * m_cells), wrap01(Z * m_cells) };
    const int G = m_mycG;
    int bi[3];
    for (int a = 0; a < 3; ++a) bi[a] = std::clamp(static_cast<int>(u[a] * G), 0, G - 1);
    const size_t b = (static_cast<size_t>(bi[0]) * G + bi[1]) * G + bi[2];
    double best = m_mycCut;
    for (int n = m_mycStart[b]; n < m_mycStart[b + 1]; ++n) {
        const mycelium::Segment& s = m_mycSegments[static_cast<size_t>(m_mycIndex[static_cast<size_t>(n)])];
        double A[3], B[3];
        for (int a = 0; a < 3; ++a) {
            const double sh = std::round(u[a] - 0.5 * (double(s.a[a]) + double(s.b[a])));   // nearest image
            A[a] = s.a[a] + sh;
            B[a] = s.b[a] + sh;
        }
        const double d = segmentDistance(u[0], u[1], u[2], A[0], A[1], A[2], B[0], B[1], B[2]) / s.w;
        if (d < best) best = d;
    }
    return best;
}

