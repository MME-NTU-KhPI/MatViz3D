    m_jitterWaves.clear();
    m_noise.clear();
    m_noise.shrink_to_fit();
    m_members.clear();
    m_members.shrink_to_fit();
    m_foamSites.clear();
    m_foamImages.clear();
    m_foamImageSite.clear();
    m_foamCells.clear();
    m_foamCells.shrink_to_fit();
    m_mycSegments.clear();
    m_mycSegments.shrink_to_fit();
    m_mycStart.clear();
    m_mycStart.shrink_to_fit();
    m_mycIndex.clear();
    m_mycIndex.shrink_to_fit();
