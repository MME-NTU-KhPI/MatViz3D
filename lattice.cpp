// TPMS level-set approximations. Arguments in radians: one cell is 2*pi.
inline double gyroidF(double X, double Y, double Z)
{
    return std::sin(X) * std::cos(Y) + std::sin(Y) * std::cos(Z) + std::sin(Z) * std::cos(X);
}

inline double schwarzPF(double X, double Y, double Z)
{
    return std::cos(X) + std::cos(Y) + std::cos(Z);
}

inline double schwarzDF(double X, double Y, double Z)
{
    const double sx = std::sin(X), cx = std::cos(X);
    const double sy = std::sin(Y), cy = std::cos(Y);
    const double sz = std::sin(Z), cz = std::cos(Z);
    return sx * sy * sz + sx * cy * cz + cx * sy * cz + cx * cy * sz;
}

inline double iwpF(double X, double Y, double Z)
{
    const double cx = std::cos(X), cy = std::cos(Y), cz = std::cos(Z);
    return 2.0 * (cx * cy + cy * cz + cz * cx)
         - (std::cos(2.0 * X) + std::cos(2.0 * Y) + std::cos(2.0 * Z));
}

// Distance from the point p to the segment ab.
inline double segmentDistance(double px, double py, double pz,
                              double ax, double ay, double az,
                              double bx, double by, double bz)
{
    const double dx = bx - ax, dy = by - ay, dz = bz - az;
    const double L2 = dx * dx + dy * dy + dz * dz;
    double t = 0.0;
    if (L2 > 0.0)
        t = std::clamp(((px - ax) * dx + (py - ay) * dy + (pz - az) * dz) / L2, 0.0, 1.0);
    const double qx = ax + t * dx - px;
    const double qy = ay + t * dy - py;
    const double qz = az + t * dz - pz;
    return std::sqrt(qx * qx + qy * qy + qz * qz);
}

inline double wrap01(double x) { return x - std::floor(x); }

// Fold a point given in cell units into the asymmetric unit of Pm-3m,
// 0 <= z <= y <= x <= 1/2: reflect each coordinate into [0, 1/2] about the
// planes x = 0 and x = 1/2 (with the period), then sort descending (the
// diagonal mirrors). The group is generated by the reflections in the walls
// of that unit, so for p and q inside it |p - q| <= |p - g q| for every
// symmetry g: the distance in the folded frame to a set inside the unit is
// the distance to the set's whole orbit.
inline void foldToUnit(double x, double y, double z, double out[3])
{
    double a = wrap01(x), b = wrap01(y), c = wrap01(z);
    a = std::min(a, 1.0 - a);
    b = std::min(b, 1.0 - b);
    c = std::min(c, 1.0 - c);
    if (a < b) std::swap(a, b);
    if (b < c) std::swap(b, c);
    if (a < b) std::swap(a, b);
    out[0] = a; out[1] = b; out[2] = c;
}

// foldToUnit that also says where each axis went: out[k] is the folded value
// of the original axis ax[k]. Needed by the thickness metric, which is not
// the same along every axis and so has to follow the axes into the unit.
inline void foldToUnitAxes(double x, double y, double z, double out[3], int ax[3])
{
    double v[3] = { wrap01(x), wrap01(y), wrap01(z) };
    for (double& a : v) a = std::min(a, 1.0 - a);
    ax[0] = 0; ax[1] = 1; ax[2] = 2;
    auto swp = [&](int i, int j) { std::swap(v[i], v[j]); std::swap(ax[i], ax[j]); };
    if (v[0] < v[1]) swp(0, 1);                    // the same three swaps as foldToUnit, so out[] is identical
    if (v[1] < v[2]) swp(1, 2);
    if (v[0] < v[1]) swp(0, 1);
    out[0] = v[0]; out[1] = v[1]; out[2] = v[2];
}

inline double dist3(const double p[3], const double q[3])
{
    const double dx = p[0] - q[0], dy = p[1] - q[1], dz = p[2] - q[2];
    return std::sqrt(dx * dx + dy * dy + dz * dz);
}

// Distance from p to the triangle abc (closest point by Voronoi regions,
// Ericson, Real-Time Collision Detection, 5.1.5). A degenerate triangle
// falls back to its three edges.
inline double triangleDistance(const double p[3], const double a[3], const double b[3], const double c[3])
{
    double ab[3], ac[3], ap[3];
    for (int i = 0; i < 3; ++i) { ab[i] = b[i] - a[i]; ac[i] = c[i] - a[i]; ap[i] = p[i] - a[i]; }
    const double nx = ab[1] * ac[2] - ab[2] * ac[1];
    const double ny = ab[2] * ac[0] - ab[0] * ac[2];
    const double nz = ab[0] * ac[1] - ab[1] * ac[0];
    if (nx * nx + ny * ny + nz * nz < 1e-18)
        return std::min({ segmentDistance(p[0], p[1], p[2], a[0], a[1], a[2], b[0], b[1], b[2]),
                          segmentDistance(p[0], p[1], p[2], b[0], b[1], b[2], c[0], c[1], c[2]),
                          segmentDistance(p[0], p[1], p[2], c[0], c[1], c[2], a[0], a[1], a[2]) });
    auto dot = [](const double* u, const double* v) { return u[0] * v[0] + u[1] * v[1] + u[2] * v[2]; };
    const double d1 = dot(ab, ap), d2 = dot(ac, ap);
    if (d1 <= 0.0 && d2 <= 0.0) return dist3(p, a);
    double bp[3]; for (int i = 0; i < 3; ++i) bp[i] = p[i] - b[i];
    const double d3 = dot(ab, bp), d4 = dot(ac, bp);
    if (d3 >= 0.0 && d4 <= d3) return dist3(p, b);
    double q[3];
    const double vc = d1 * d4 - d3 * d2;
    if (vc <= 0.0 && d1 >= 0.0 && d3 <= 0.0) {
        const double v = d1 / (d1 - d3);
        for (int i = 0; i < 3; ++i) q[i] = a[i] + v * ab[i];
        return dist3(p, q);
    }
    double cp[3]; for (int i = 0; i < 3; ++i) cp[i] = p[i] - c[i];
    const double d5 = dot(ab, cp), d6 = dot(ac, cp);
    if (d6 >= 0.0 && d5 <= d6) return dist3(p, c);
    const double vb = d5 * d2 - d1 * d6;
    if (vb <= 0.0 && d2 >= 0.0 && d6 <= 0.0) {
        const double w = d2 / (d2 - d6);
        for (int i = 0; i < 3; ++i) q[i] = a[i] + w * ac[i];
        return dist3(p, q);
    }
    const double va = d3 * d6 - d5 * d4;
    if (va <= 0.0 && (d4 - d3) >= 0.0 && (d5 - d6) >= 0.0) {
        const double w = (d4 - d3) / ((d4 - d3) + (d5 - d6));
        for (int i = 0; i < 3; ++i) q[i] = b[i] + w * (c[i] - b[i]);
        return dist3(p, q);
    }
    const double den = 1.0 / (va + vb + vc);
    const double v = vb * den, w = vc * den;
    for (int i = 0; i < 3; ++i) q[i] = a[i] + ab[i] * v + ac[i] * w;
    return dist3(p, q);
}

// Area A of the mid-surface f = 0 in one unit cell of edge 1, for the mean sheet
// thickness t ~ rho * a / A (volume of the sheet = area x thickness); an estimate
// only, used to warn about thin walls.
//
// Source of the numbers: the area of the level set this file builds (the
// trigonometric approximations above, and the expansions of cellforms::tpmsWaves()
// for the last three), computed by triangulating f = 0 with marching cubes on
// periodic grids of 96, 192 and 320 points per edge and extrapolating to zero
// spacing. A second method, the volume of the layer |f| / |grad f| < h divided by
// 2 h, gives the same values within 0.3 %.
//
// Reference for the minimal surfaces themselves, same conventional cubic cell:
// U. S. Schwarz, G. Gompper, Phys. Rev. E 59 (1999) 5528-5541,
// doi:10.1103/PhysRevE.59.5528, arXiv:cond-mat/9903406 (Table 1: exact, from the
// Weierstrass representation; Table 3: numerical). The approximations of the
// gyroid, Schwarz P, Schwarz D and Fischer-Koch S are within 0.4 % of them. Those
// of I-WP and Neovius are not (+2.6 % and -7.5 %), so the area of the approximation
// is what counts here. The Lidinoid is used in a cubic cell and has no tabulated value.
inline double tpmsAreaPerCell(LatticeFamily f)
{
    switch (f) {
        //                                                    computed   minimal surface (reference)
        case LatticeFamily::GyroidSheet:      return 3.09;   // 3.0916     3.0914  (G)
        case LatticeFamily::SchwarzPSheet:    return 2.35;   // 2.3526     2.3451  (P)
        case LatticeFamily::SchwarzDSheet:    return 3.84;   // 3.8380     3.8378  (D)
        case LatticeFamily::IWPSheet:         return 3.55;   // 3.5536     3.4641  (I-WP)
        case LatticeFamily::NeoviusSheet:     return 3.52;   // 3.5236     3.8094  (C(P), Table 3)
        case LatticeFamily::FischerKochSheet: return 5.43;   // 5.4301     5.4145  (S, Table 3)
        case LatticeFamily::LidinoidSheet:    return 6.24;   // 6.2386     -
        default:                              return 0.0;
    }
}

// Exact Fourier expansions of the newer minimal surfaces, built once.
const std::vector<cellforms::Wave>& surfaceWaves(LatticeFamily f)
{
    static const std::vector<cellforms::Wave> neo = cellforms::tpmsWaves(cellforms::Surface::Neovius);
    static const std::vector<cellforms::Wave> fks = cellforms::tpmsWaves(cellforms::Surface::FischerKochS);
    static const std::vector<cellforms::Wave> lid = cellforms::tpmsWaves(cellforms::Surface::Lidinoid);
    switch (f) {
        case LatticeFamily::NeoviusSheet:     return neo;
        case LatticeFamily::FischerKochSheet: return fks;
        default:                              return lid;
    }
}

inline bool isNewSurface(LatticeFamily f)
{
    return f == LatticeFamily::NeoviusSheet || f == LatticeFamily::FischerKochSheet || f == LatticeFamily::LidinoidSheet;
}

